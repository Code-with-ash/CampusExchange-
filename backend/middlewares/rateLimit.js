import rateLimit from 'express-rate-limit'

const standardMessage = {
  success: false,
  message: 'Too many requests. Please try again later.',
}

export const authRateLimit = rateLimit({
  windowMs: 15 * 60 * 1000,
  limit: 10,
  standardHeaders: 'draft-8',
  legacyHeaders: false,
  message: standardMessage,
})

